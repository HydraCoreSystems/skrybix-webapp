# Shared logic
# ----------------------------------------------------------------
def next_cutting_seq(db, mother_id):
    """Highest existing sequence number for this mother's cuttings, +1.
    Uses zero-padded width that grows past 99 instead of truncating
    (the bug in the original Apps Script: ('0'+seq).slice(-2))."""
    prefix = mother_id + "-C"
    rows = db.execute(
        "SELECT cutting_id FROM cuttings WHERE cutting_id LIKE ?", (prefix + "%",)
    ).fetchall()
    max_seq = 0
    for r in rows:
        tail = r["cutting_id"][len(prefix):]
        if tail.isdigit():
            max_seq = max(max_seq, int(tail))
    return max_seq + 1


def make_cutting_id(mother_id, seq):
    width = 2 if seq < 100 else len(str(seq))
    return f"{mother_id}-C{str(seq).zfill(width)}"


def qr_png_bytes(url_text):
    img = qrcode.make(url_text, box_size=6, border=2)
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    buf.seek(0)
    return buf


