@app.route("/")
def dashboard():
    db = get_db()
    mother_count = db.execute("SELECT COUNT(*) c FROM mother_plants").fetchone()["c"]
    cutting_count = db.execute("SELECT COUNT(*) c FROM cuttings WHERE sold = 0").fetchone()["c"]
    sold_pending = db.execute("SELECT COUNT(*) c FROM cuttings WHERE sold = 1").fetchone()["c"]
    outgoing_count = db.execute("SELECT COUNT(*) c FROM outgoing_log").fetchone()["c"]
    print_mothers = db.execute("SELECT COUNT(*) c FROM mother_plants WHERE print_label = 1").fetchone()["c"]
    print_cuttings = db.execute("SELECT COUNT(*) c FROM cuttings WHERE print_label = 1").fetchone()["c"]
    recent_outgoing = db.execute(
        "SELECT * FROM outgoing_log ORDER BY id DESC LIMIT 8"
    ).fetchall()
    return render_template(
        "dashboard.html",
        mother_count=mother_count,
        cutting_count=cutting_count,
        sold_pending=sold_pending,
        outgoing_count=outgoing_count,
        print_mothers=print_mothers,
        print_cuttings=print_cuttings,
        recent_outgoing=recent_outgoing,
    )


