@app.route("/cuttings")
def cuttings_list():
    db = get_db()
    rows = db.execute(
        """SELECT c.*, m.display_name AS mother_display_name
           FROM cuttings c JOIN mother_plants m ON m.mother_id = c.mother_id
           ORDER BY c.created_at DESC"""
    ).fetchall()
    return render_template("cuttings.html", rows=rows)


@app.route("/cuttings/new", methods=["GET", "POST"])
def cuttings_new():
    db = get_db()
    mothers = db.execute("SELECT * FROM mother_plants ORDER BY mother_id").fetchall()
    if request.method == "POST":
        mother_id = request.form["mother_id"]
        num_cuts = int(request.form.get("num_cuts", 0) or 0)
        date_taken = request.form.get("date_taken") or date.today().isoformat()

        mother = db.execute(
            "SELECT * FROM mother_plants WHERE mother_id = ?", (mother_id,)
        ).fetchone()
        if not mother:
            flash("Unknown mother plant.", "error")
            return redirect(url_for("cuttings_new"))
        if num_cuts < 1:
            flash("Number of cuttings must be at least 1.", "error")
            return redirect(url_for("cuttings_new"))

        seq = next_cutting_seq(db, mother_id)
        created = []
        for n in range(num_cuts):
            cid = make_cutting_id(mother_id, seq + n)
            db.execute(
                """INSERT INTO cuttings
                   (cutting_id, mother_id, full_display_name, label_line1, label_line2,
                    date_taken, sold, print_label, created_at)
                   VALUES (?, ?, ?, ?, ?, ?, 0, 0, ?)""",
                (
                    cid,
                    mother_id,
                    mother["display_name"],
                    mother["botanical_line1"],
                    mother["botanical_line2"],
                    date_taken,
                    datetime.utcnow().isoformat(),
                ),
            )
            created.append(cid)
        db.commit()
        flash(f"Created {len(created)} cutting(s): {', '.join(created)}", "success")
        return redirect(url_for("cuttings_list"))
    return render_template("cutting_new.html", mothers=mothers)


@app.route("/cuttings/<cutting_id>/toggle", methods=["POST"])
def cuttings_toggle(cutting_id):
    db = get_db()
    field = request.form["field"]  # "sold" or "print_label"
    if field not in ("sold", "print_label"):
        abort(400)
    row = db.execute("SELECT * FROM cuttings WHERE cutting_id=?", (cutting_id,)).fetchone()
    if not row:
        abort(404)
    new_val = 0 if row[field] else 1
    db.execute(f"UPDATE cuttings SET {field}=? WHERE cutting_id=?", (new_val, cutting_id))
    db.commit()
    return redirect(url_for("cuttings_list"))


