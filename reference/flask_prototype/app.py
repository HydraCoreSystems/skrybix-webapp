def build_label_pdf(items):
    """items: list of dicts with id_text, line1, line2, qr_url. Renders a
    grid of Avery-5160-ish labels (3 cols) with a real per-item QR code."""
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=letter)
    page_w, page_h = letter

    margin_x = 0.19 * inch
    margin_y = 0.5 * inch
    label_w = 2.6 * inch
    label_h = 1.0 * inch
    gap_x = 0.19 * inch
    cols = 3
    rows_per_page = int((page_h - 2 * margin_y) // label_h)

    col = 0
    row = 0
    for item in items:
        if row >= rows_per_page:
            c.showPage()
            row = 0
        x = margin_x + col * (label_w + gap_x)
        y = page_h - margin_y - (row + 1) * label_h

        c.rect(x, y, label_w, label_h)

        qr_buf = qr_png_bytes(item["qr_url"])
        qr_size = label_h - 0.15 * inch
        c.drawImage(
            ImageReader(qr_buf), x + 0.05 * inch, y + 0.075 * inch,
            width=qr_size, height=qr_size, preserveAspectRatio=True, mask="auto",
        )

        text_x = x + qr_size + 0.15 * inch
        c.setFont("Helvetica-Bold", 8)
        c.drawString(text_x, y + label_h - 0.25 * inch, item["id_text"][:26])
        c.setFont("Helvetica", 7)
        c.drawString(text_x, y + label_h - 0.45 * inch, (item["line1"] or "")[:28])
        c.drawString(text_x, y + label_h - 0.62 * inch, (item["line2"] or "")[:28])

        col += 1
        if col >= cols:
            col = 0
            row += 1

    c.save()
    buf.seek(0)
    return buf


