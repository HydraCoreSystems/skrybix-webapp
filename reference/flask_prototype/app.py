@app.route("/push_sold", methods=["POST"])
def push_sold():
    db = get_db()
    sold_rows = db.execute("SELECT * FROM cuttings WHERE sold = 1").fetchall()
    today = date.today().isoformat()
    pushed = 0
    for r in sold_rows:
        existing = db.execute(
            "SELECT 1 FROM outgoing_log WHERE cutting_id=?", (r["cutting_id"],)
        ).fetchone()
        if not existing:
            db.execute(
                """INSERT INTO outgoing_log (date_out, cutting_id, full_display_name, qty, reason)
                   VALUES (?, ?, ?, 1, 'Sale')""",
                (today, r["cutting_id"], r["full_display_name"]),
            )
            pushed += 1
        db.execute("UPDATE cuttings SET sold=0 WHERE cutting_id=?", (r["cutting_id"],))
    db.commit()
    flash(f"Pushed {pushed} sold cutting(s) to Outgoing Log.", "success")
    return redirect(url_for("cuttings_list"))


