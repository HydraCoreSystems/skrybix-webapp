def build_csv(header, rows):
    buf = io.StringIO()
    writer = csv.writer(buf)  # csv module handles quoting/escaping correctly, no manual join(',')
    writer.writerow(header)
    for r in rows:
        writer.writerow(r)
    mem = io.BytesIO(buf.getvalue().encode("utf-8"))
    mem.seek(0)
    return mem


