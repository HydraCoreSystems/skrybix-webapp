"""
Skrybix Web — minimal working prototype

This is a proof-of-concept replacement for the Google Sheets + Apps Script
version of Skrybix. It reproduces the same core workflow:

  Mother Plants  --(take cuttings)-->  Cuttings  --(sold)-->  Outgoing Log
                                          |
                                          +--> printable labels (CSV + PDF, with real QR codes)

What this fixes vs. the Sheets version, by construction:
  - CSV export uses Python's csv module, so commas/quotes in plant names
    can never corrupt the file (the original Apps Script did naive
    string.join(',') with no escaping).
  - Every cutting gets its own correctly-derived QR code, generated at
    export time from its own Cutting_ID/Mother_ID (the Sheets version
    copied one hardcoded QR value from row 2 onto every new cutting).
  - IDs are generated by a single get_or_create sequence per mother with
    no fixed-width truncation, so id numbering doesn't wrap past 99.
  - All writes go through a real SQLite database with transactions,
    instead of direct cell writes that can race with onEdit/onFormSubmit
    triggers firing concurrently.
  - This is a *prototype*, not a production app: no auth, no multi-user
    permissions, no hosting config. See the review doc for what a real
    rollout would still need (auth, backups, a proper printer pipeline).

Run:
    pip install -r requirements.txt
    python app.py
Then open http://127.0.0.1:5000
"""
import csv
