@app.route("/mothers")
def mothers_list():
    db = get_db()
    rows = db.execute("SELECT * FROM mother_plants ORDER BY mother_id").fetchall()
    return render_template("mothers.html", rows=rows)


@app.route("/mothers/new", methods=["GET", "POST"])
def mothers_new():
    db = get_db()
    if request.method == "POST":
        mother_id = request.form["mother_id"].strip()
        if not mother_id:
            flash("Mother ID is required.", "error")
            return redirect(url_for("mothers_new"))
        existing = db.execute(
            "SELECT 1 FROM mother_plants WHERE mother_id = ?", (mother_id,)
        ).fetchone()
        if existing:
            flash(f'Mother ID "{mother_id}" already exists.', "error")
            return redirect(url_for("mothers_new"))
        db.execute(
            """INSERT INTO mother_plants
               (mother_id, display_name, location, botanical_line1, botanical_line2, print_label, created_at)
               VALUES (?, ?, ?, ?, ?, 0, ?)""",
            (
                mother_id,
                request.form.get("display_name", "").strip(),
                request.form.get("location", "").strip(),
                request.form.get("botanical_line1", "").strip(),
                request.form.get("botanical_line2", "").strip(),
                datetime.utcnow().isoformat(),
            ),
        )
        db.commit()
        flash(f'Mother plant "{mother_id}" added.', "success")
        return redirect(url_for("mothers_list"))
    return render_template("mother_form.html", mother=None)


