DB_PATH = "skrybix.db"

app = Flask(__name__)
app.secret_key = "skrybix-prototype-dev-key"  # fine for a local prototype only


# ----------------------------------------------------------------
# DB helpers
# ----------------------------------------------------------------
def get_db():
    if "db" not in g:
        g.db = sqlite3.connect(DB_PATH)
        g.db.row_factory = sqlite3.Row
        g.db.execute("PRAGMA foreign_keys = ON")
    return g.db


@app.teardown_appcontext
def close_db(exception=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def init_db():
    db = sqlite3.connect(DB_PATH)
    db.executescript(
        """
        CREATE TABLE IF NOT EXISTS mother_plants (
            mother_id       TEXT PRIMARY KEY,
            display_name    TEXT NOT NULL,
            location        TEXT,
            botanical_line1 TEXT,
            botanical_line2 TEXT,
            print_label     INTEGER NOT NULL DEFAULT 0,
            created_at      TEXT NOT NULL
        );

        CREATE TABLE IF NOT EXISTS cuttings (
            cutting_id        TEXT PRIMARY KEY,
            mother_id         TEXT NOT NULL REFERENCES mother_plants(mother_id),
            full_display_name TEXT,
            label_line1       TEXT,
            label_line2       TEXT,
            date_taken        TEXT,
            sold              INTEGER NOT NULL DEFAULT 0,
            print_label       INTEGER NOT NULL DEFAULT 0,
            created_at        TEXT NOT NULL
        );

        CREATE TABLE IF NOT EXISTS outgoing_log (
            id                 INTEGER PRIMARY KEY AUTOINCREMENT,
            date_out           TEXT NOT NULL,
            cutting_id         TEXT NOT NULL,
            full_display_name  TEXT,
            qty                INTEGER NOT NULL DEFAULT 1,
            reason             TEXT,
            selling_platform   TEXT,
            notes              TEXT
        );
        """
    )
    db.commit()
    db.close()


